// Mobile Navigation Panel Trigger Control
function initializeMobileNavigationOverlay() {
    const trigger = document.getElementById("menu-trigger");
    const navMenu = document.getElementById("nav-menu");
    const baseLinks = document.querySelectorAll(".interactive-nav-link");

    if(trigger && navMenu) {
        trigger.addEventListener("click", () => {
            trigger.classList.toggle("menu-active");
            navMenu.classList.toggle("open-menu");
        });

        baseLinks.forEach(lnk => {
            lnk.addEventListener("click", () => {
                trigger.classList.remove("menu-active");
                navMenu.classList.remove("open-menu");
                baseLinks.forEach(l => l.classList.remove("active"));
                lnk.classList.add("active");
            });
        });
    }
}

// Portfolio Grid Filter Systems Sorting Engine
function initializePortfolioFilters() {
    const filtersHub = document.getElementById("portfolio-filter-hub");
    if(!filtersHub) return;

    const filterButtons = filtersHub.querySelectorAll(".filter-pill-btn");
    const portfolioCards = document.querySelectorAll(".portfolio-wrapper-node");

    filterButtons.forEach(btn => {
        btn.addEventListener("click", () => {
            filterButtons.forEach(b => b.classList.remove("active"));
            btn.classList.add("active");

            const targetedCategory = btn.getAttribute("data-target-category");

            portfolioCards.forEach(card => {
                const cardCat = card.getAttribute("data-item-category");
                if(targetedCategory === "all" || cardCat === targetedCategory) {
                    card.style.display = "block";
                    setTimeout(() => card.style.opacity = "1", 50);
                } else {
                    card.style.opacity = "0";
                    setTimeout(() => card.style.display = "none", 400);
                }
            });
        });
    });
}

// Image Lightbox System Controller
function initializeLightboxModal() {
    const lightbox = document.getElementById("global-lightbox");
    const closeBtn = document.getElementById("lightbox-close");
    const targetImg = document.getElementById("lightbox-target-img");
    const targetTitle = document.getElementById("lightbox-target-title");
    const targetDesc = document.getElementById("lightbox-target-desc");

    if(!lightbox) return;

    document.addEventListener("click", (e) => {

    const trigger = e.target.closest(".lightbox-trigger-anchor");

    if(trigger) {

        e.preventDefault();

        const src = trigger.getAttribute("data-img-src");
        const heading = trigger.getAttribute("data-title");
        const summary = trigger.getAttribute("data-desc");

        if(targetImg && src) {

            targetImg.src = src;

            if(targetTitle)
                targetTitle.textContent = heading;

            if(targetDesc)
                targetDesc.textContent = summary;

            lightbox.classList.add("open");
        }
    }
});

    if(closeBtn) {
        closeBtn.addEventListener("click", () => lightbox.classList.remove("open"));
    }
    lightbox.addEventListener("click", (e) => {
        if(e.target === lightbox) lightbox.classList.remove("open");
    });
}

// Reviews Slider Core Interval Engine
function initializeReviewSliderEngine() {
    let internalCurrentIndex = 0;
    const arrowLeft = document.getElementById("slider-left-arrow");
    const arrowRight = document.getElementById("slider-right-arrow");

    function displayTargetSlide(targetIdx) {
        const structuralSlides = document.querySelectorAll(".review-slider-slide");
        if(structuralSlides.length === 0) return;
        
        structuralSlides.forEach(s => s.classList.remove("visible-slide"));
        
        if(targetIdx >= structuralSlides.length) internalCurrentIndex = 0;
        else if (targetIdx < 0) internalCurrentIndex = structuralSlides.length - 1;
        else internalCurrentIndex = targetIdx;

        structuralSlides[internalCurrentIndex].classList.add("visible-slide");
    }

    if(arrowRight && arrowLeft) {
        arrowRight.addEventListener("click", () => displayTargetSlide(internalCurrentIndex + 1));
        arrowLeft.addEventListener("click", () => displayTargetSlide(internalCurrentIndex - 1));
    }
}

// Accordion Collapsible Drawers (FAQ)
function initializeAccordionDrawers() {
    document.addEventListener("click", (e) => {
        const header = e.target.closest(".accordion-header-block");
        if(!header) return;

        const containerNode = header.parentElement;
        const drawer = containerNode.querySelector(".accordion-body-drawer");

        if(containerNode.classList.contains("expanded")) {
            drawer.style.maxHeight = "0px";
            containerNode.classList.remove("expanded");
        } else {
            drawer.style.maxHeight = drawer.scrollHeight + "px";
            containerNode.classList.add("expanded");
        }
    });
}

// Numerical Auto Counters Incremental Calculator
function animateNumericalCounters() {
    const counterElements = document.querySelectorAll(".operational-counter");
    counterElements.forEach(cnt => {
        const targetValue = parseInt(cnt.getAttribute("data-target-max"), 10);
        let startPoint = 0;
        const pacingDuration = Math.floor(2000 / targetValue);
        
        const runtimeInterval = setInterval(() => {
            startPoint++;
            cnt.textContent = startPoint;
            if(startPoint >= targetValue) {
                clearInterval(runtimeInterval);
                cnt.textContent = targetValue; // Hard-clamp execution
            }
        }, pacingDuration > 10 ? pacingDuration : 10);
    });
}

// Pure Intersection Observer Viewport Reveal Engine
function initializeScrollReveals() {
    const elementsToReveal = document.querySelectorAll(".scroll-reveal");
    
    const visualObserver = new IntersectionObserver((entries) => {
        entries.forEach(entry => {
            if(entry.isIntersecting) {
                entry.target.classList.add("reveal-visible");
                visualObserver.unobserve(entry.target); // Unregister performance handler
            }
        });
    }, { threshold: 0.1, rootMargin: "0px 0px -40px 0px" });

    elementsToReveal.forEach(el => visualObserver.observe(el));
}

